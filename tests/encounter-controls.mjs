import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const out='test-results/encounter-controls';await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:960},reducedMotion:'reduce'});
const checks=[],errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(process.env.TRIO_URL||'http://127.0.0.1:4173/');
 await page.getByTestId('case-quest').click();
 await page.getByLabel('Story playback speed',{exact:true}).selectOption('4');
 await page.getByLabel('Start demo',{exact:true}).click();
 const player=page.getByTestId('trio-player');
 await expect(player).toHaveAttribute('data-step','minimal',{timeout:30000});
 await expect(player).toHaveAttribute('data-phase','reading');
 const first=page.getByTestId('canvas-object-minimal');
 await expect(first.getByTestId('materialize-surface')).toHaveAttribute('data-state','ready');
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
 await expect(page.getByLabel('Resume story',{exact:true})).toBeVisible();
 const hp=await first.getByRole('progressbar',{name:'pip HP',exact:true}).getAttribute('aria-valuenow');
 await page.waitForTimeout(1500);
 await expect(first.getByRole('progressbar',{name:'pip HP',exact:true})).toHaveAttribute('aria-valuenow',hp);
 await expect(player).toHaveAttribute('data-step','minimal');
 await page.evaluate(()=>{delete document.hidden;document.dispatchEvent(new Event('visibilitychange'));});
 await expect(page.getByLabel('Resume story',{exact:true})).toBeVisible();
 await page.getByLabel('Resume story',{exact:true}).click();
 checks.push('Hidden document pauses guided story and game; returning requires explicit resume, including reduced motion');
 await expect(player).toHaveAttribute('data-step','verify',{timeout:30000});
 await expect(player).toHaveAttribute('data-phase','reading');
 await page.getByLabel('Take over workspace',{exact:true}).click();
 await page.getByRole('button',{name:'Teach a rule',exact:true}).click();
 const draft=page.getByTestId('canvas-object-teach');
 await draft.getByText('ดูและปรับกติกาโล่',{exact:true}).click();
 await draft.getByLabel('ลดความเสียหาย HP',{exact:true}).fill('3');
 await page.getByLabel('Save workspace',{exact:true}).click();
 const read=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('procedural.trio.manual.v1.quest')).snapshot);
 let saved=await read();expect(saved.evaluation).toBeNull();expect(saved.active.quest.encounter.allyShield).toBe(false);expect(saved.draft.quest.encounter.shieldReduction).toBe(3);
 const composer=page.getByLabel('Describe a rule change',{exact:true});
 await composer.fill('อนุมัติกติกานี้');await composer.press('Enter');
 await page.getByLabel('Save workspace',{exact:true}).click();
 saved=await read();expect(saved.version).toBe(1);expect(saved.approved).toBe(false);
 checks.push('Manual shield edit invalidates previous verification; approval cannot promote an untested rule');
 await page.screenshot({path:`${out}/manual-rule.png`});
 expect(errors).toEqual([]);await writeFile(`${out}/report.json`,JSON.stringify({checks,errors},null,2));console.log(JSON.stringify({checks,errors}));
}catch(e){await page.screenshot({path:`${out}/failure.png`});throw e;}finally{await browser.close();}
